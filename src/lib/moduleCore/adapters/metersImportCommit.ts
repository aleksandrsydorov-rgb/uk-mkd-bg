/**
 * IS-3 meter inventory commit safety.
 * Atomic multi-row assign is NOT available without a new SECURITY DEFINER bulk RPC
 * (would require migration / domain rewrite). This module implements explicit per-row
 * outcomes while still calling canonical assign_* one row at a time.
 */

import type { ImportPreviewResult } from '@/lib/moduleCore/types';
import {
  type ElectricityAssignPayload,
  type ExistingMeterRef,
  type WaterAssignPayload,
  electricityAssignPayloadsFromPreview,
  waterAssignPayloadsFromPreview,
} from '@/lib/moduleCore/adapters/metersOpening';

export const METER_COMMIT_OUTCOMES = [
  'CREATED',
  'SKIPPED_EXISTING',
  'FAILED',
  'NOT_PROCESSED',
] as const;

export type MeterCommitOutcome = (typeof METER_COMMIT_OUTCOMES)[number];

export type MeterCommitRowResult = {
  rowNumber: number;
  apartmentNumber: string;
  meterNumber: string;
  propertyId: number;
  outcome: MeterCommitOutcome;
  detail: string;
  /** True when assign_* was invoked for this row. */
  attempted: boolean;
};

export type MeterCommitBatchResult = {
  utility: 'water' | 'electricity';
  rows: MeterCommitRowResult[];
  createdCount: number;
  skippedExistingCount: number;
  failedCount: number;
  notProcessedCount: number;
  /** True only when every intended CREATE was CREATED or SKIPPED_EXISTING and none FAILED/NOT_PROCESSED. */
  fullySuccessful: boolean;
  /** submit_* never called — charges never generated by this path. */
  chargesGenerated: false;
  stoppedEarly: boolean;
};

export type AssignWaterFn = (
  payload: WaterAssignPayload,
) => Promise<{ ok: true } | { ok: false; message: string }>;

export type AssignElectricityFn = (
  payload: ElectricityAssignPayload,
) => Promise<{ ok: true } | { ok: false; message: string }>;

export function classifyAssignErrorMessage(message: string): MeterCommitOutcome {
  const msg = message.toLowerCase();
  if (msg.includes('already assigned')) return 'SKIPPED_EXISTING';
  // Unique serial collision — treat as conflict failure (may be another apartment).
  if (msg.includes('already in use')) return 'FAILED';
  if (msg.includes('not authorized')) return 'FAILED';
  return 'FAILED';
}

type PlannedRow = {
  rowNumber: number;
  apartmentNumber: string;
  meterNumber: string;
  propertyId: number;
  kind: 'skip_preview' | 'create';
  water?: WaterAssignPayload;
  electricity?: ElectricityAssignPayload;
};

function planRowsFromPreview(
  utility: 'water' | 'electricity',
  preview: ImportPreviewResult,
): PlannedRow[] {
  const planned: PlannedRow[] = [];
  for (const row of preview.rows) {
    const apartmentNumber = String(row.data.apartment_number ?? '').trim();
    const meterNumber = String(row.data.meter_number ?? '').trim();
    const propertyId = Number(row.data.resolved_property_id);
    if (row.operation === 'skip') {
      planned.push({
        rowNumber: row.rowNumber,
        apartmentNumber,
        meterNumber,
        propertyId: Number.isFinite(propertyId) ? propertyId : 0,
        kind: 'skip_preview',
      });
      continue;
    }
    if (row.operation !== 'create') continue;
    // Error rows are never planned for assign.
  }

  if (utility === 'water') {
    const payloads = waterAssignPayloadsFromPreview(preview);
    const byKey = new Map(
      payloads.map((p) => [`${p.propertyId}|${p.meterNumber.trim().toLowerCase()}`, p]),
    );
    for (const row of preview.rows) {
      if (row.operation !== 'create') continue;
      const apartmentNumber = String(row.data.apartment_number ?? '').trim();
      const meterNumber = String(row.data.meter_number ?? '').trim();
      const propertyId = Number(row.data.resolved_property_id);
      const payload = byKey.get(`${propertyId}|${meterNumber.toLowerCase()}`);
      if (!payload) continue;
      planned.push({
        rowNumber: row.rowNumber,
        apartmentNumber,
        meterNumber,
        propertyId,
        kind: 'create',
        water: payload,
      });
    }
  } else {
    const payloads = electricityAssignPayloadsFromPreview(preview);
    const byKey = new Map(
      payloads.map((p) => [`${p.propertyId}|${p.meterNumber.trim().toLowerCase()}`, p]),
    );
    for (const row of preview.rows) {
      if (row.operation !== 'create') continue;
      const apartmentNumber = String(row.data.apartment_number ?? '').trim();
      const meterNumber = String(row.data.meter_number ?? '').trim();
      const propertyId = Number(row.data.resolved_property_id);
      const payload = byKey.get(`${propertyId}|${meterNumber.toLowerCase()}`);
      if (!payload) continue;
      planned.push({
        rowNumber: row.rowNumber,
        apartmentNumber,
        meterNumber,
        propertyId,
        kind: 'create',
        electricity: payload,
      });
    }
  }

  return planned.sort((a, b) => a.rowNumber - b.rowNumber);
}

function summarize(utility: 'water' | 'electricity', rows: MeterCommitRowResult[], stoppedEarly: boolean): MeterCommitBatchResult {
  const createdCount = rows.filter((r) => r.outcome === 'CREATED').length;
  const skippedExistingCount = rows.filter((r) => r.outcome === 'SKIPPED_EXISTING').length;
  const failedCount = rows.filter((r) => r.outcome === 'FAILED').length;
  const notProcessedCount = rows.filter((r) => r.outcome === 'NOT_PROCESSED').length;
  const fullySuccessful =
    failedCount === 0 &&
    notProcessedCount === 0 &&
    rows.every((r) => r.outcome === 'CREATED' || r.outcome === 'SKIPPED_EXISTING');
  return {
    utility,
    rows,
    createdCount,
    skippedExistingCount,
    failedCount,
    notProcessedCount,
    fullySuccessful,
    chargesGenerated: false,
    stoppedEarly,
  };
}

/**
 * Execute inventory commit with per-row outcomes.
 * Stops assigning after the first FAILED create attempt; remaining creates → NOT_PROCESSED.
 * Preview SKIP rows are recorded as SKIPPED_EXISTING without calling assign_*.
 */
export async function commitMeterInventoryBatch(args: {
  utility: 'water' | 'electricity';
  preview: ImportPreviewResult;
  assignWater: AssignWaterFn;
  assignElectricity: AssignElectricityFn;
}): Promise<MeterCommitBatchResult> {
  const planned = planRowsFromPreview(args.utility, args.preview);
  const results: MeterCommitRowResult[] = [];
  let stopAssign = false;

  for (const item of planned) {
    if (item.kind === 'skip_preview') {
      results.push({
        rowNumber: item.rowNumber,
        apartmentNumber: item.apartmentNumber,
        meterNumber: item.meterNumber,
        propertyId: item.propertyId,
        outcome: 'SKIPPED_EXISTING',
        detail: 'preview_active_meter',
        attempted: false,
      });
      continue;
    }

    if (stopAssign) {
      results.push({
        rowNumber: item.rowNumber,
        apartmentNumber: item.apartmentNumber,
        meterNumber: item.meterNumber,
        propertyId: item.propertyId,
        outcome: 'NOT_PROCESSED',
        detail: 'stopped_after_prior_failure',
        attempted: false,
      });
      continue;
    }

    const assignResult =
      args.utility === 'water'
        ? await args.assignWater(item.water!)
        : await args.assignElectricity(item.electricity!);

    if (assignResult.ok) {
      results.push({
        rowNumber: item.rowNumber,
        apartmentNumber: item.apartmentNumber,
        meterNumber: item.meterNumber,
        propertyId: item.propertyId,
        outcome: 'CREATED',
        detail: 'assign_ok',
        attempted: true,
      });
      continue;
    }

    const outcome = classifyAssignErrorMessage(assignResult.message);
    results.push({
      rowNumber: item.rowNumber,
      apartmentNumber: item.apartmentNumber,
      meterNumber: item.meterNumber,
      propertyId: item.propertyId,
      outcome,
      detail: assignResult.message,
      attempted: true,
    });
    if (outcome === 'FAILED') {
      stopAssign = true;
    }
    // SKIPPED_EXISTING (concurrent race / already assigned) — continue; idempotent.
  }

  return summarize(args.utility, results, stopAssign);
}

/**
 * Reconcile reported outcomes against live meter rows (authoritative DB state).
 * Does not overwrite baselines; only upgrades NOT_PROCESSED/FAILED when an active
 * meter already matches apartment or serial (concurrent winner / prior partial).
 */
export function reconcileMeterCommitWithDb(
  batch: MeterCommitBatchResult,
  meters: ExistingMeterRef[],
): MeterCommitBatchResult {
  const activeByProperty = new Set<number>();
  const serialToProperty = new Map<string, number>();
  for (const m of meters) {
    if (m.retiredAt != null && m.retiredAt !== '') continue;
    activeByProperty.add(m.propertyId);
    serialToProperty.set(m.meterNumber.trim().toLowerCase(), m.propertyId);
  }

  const rows = batch.rows.map((row) => {
    if (row.outcome === 'CREATED' || row.outcome === 'SKIPPED_EXISTING') return row;
    const serialKey = row.meterNumber.trim().toLowerCase();
    const serialOwner = serialToProperty.get(serialKey);
    const hasActive = activeByProperty.has(row.propertyId);
    if (hasActive || serialOwner === row.propertyId) {
      return {
        ...row,
        outcome: 'SKIPPED_EXISTING' as const,
        detail: `${row.detail}|reconciled_active_present`,
      };
    }
    return row;
  });

  return summarize(batch.utility, rows, batch.stoppedEarly);
}

/** Rows safe to retry: FAILED or NOT_PROCESSED that still lack an active meter. */
export function retryCandidatesFromBatch(
  batch: MeterCommitBatchResult,
  meters: ExistingMeterRef[],
): MeterCommitRowResult[] {
  const activeByProperty = new Set(
    meters.filter((m) => m.retiredAt == null || m.retiredAt === '').map((m) => m.propertyId),
  );
  return batch.rows.filter(
    (r) =>
      (r.outcome === 'FAILED' || r.outcome === 'NOT_PROCESSED') &&
      !activeByProperty.has(r.propertyId),
  );
}

/** Narrow preview to CREATE rows that still need assign (for retry upload reuse). */
export function filterPreviewForRetry(
  preview: ImportPreviewResult,
  retryRowNumbers: Set<number>,
): ImportPreviewResult {
  const rows = preview.rows.filter(
    (r) => r.operation === 'create' && retryRowNumbers.has(r.rowNumber),
  );
  return {
    schemaVersion: preview.schemaVersion,
    rows,
    createCount: rows.length,
    updateCount: 0,
    skipCount: 0,
    errorCount: 0,
  };
}

/** Merge a retry batch into a prior result (by rowNumber). */
export function mergeMeterCommitBatches(
  prior: MeterCommitBatchResult,
  retry: MeterCommitBatchResult,
): MeterCommitBatchResult {
  const byRow = new Map(prior.rows.map((r) => [r.rowNumber, r]));
  for (const r of retry.rows) {
    byRow.set(r.rowNumber, r);
  }
  const rows = [...byRow.values()].sort((a, b) => a.rowNumber - b.rowNumber);
  return summarize(prior.utility, rows, retry.stoppedEarly);
}

export function meterCommitAuditPayload(batch: MeterCommitBatchResult): Record<string, unknown> {
  return {
    utility: batch.utility,
    fullySuccessful: batch.fullySuccessful,
    stoppedEarly: batch.stoppedEarly,
    chargesGenerated: batch.chargesGenerated,
    createdCount: batch.createdCount,
    skippedExistingCount: batch.skippedExistingCount,
    failedCount: batch.failedCount,
    notProcessedCount: batch.notProcessedCount,
    rows: batch.rows.map((r) => ({
      rowNumber: r.rowNumber,
      apartmentNumber: r.apartmentNumber,
      meterNumber: r.meterNumber,
      propertyId: r.propertyId,
      outcome: r.outcome,
      detail: r.detail,
      attempted: r.attempted,
    })),
    opening_reading_row_commit: 'BLOCKED',
    atomic_transaction: false,
  };
}
