  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  apartment_number text not null,
  floor integer null,
  section_code text null,
  block_code text null,
  area_sqm numeric null,
  status text null,
  owner_name text null,
  owner_phone text null,
  owner_email text null,
  debt numeric null,
  overpayment numeric null,
  electricity_meter_number text null,
  occupancy_status text null,
  pet_info text null,
  owner_type text null,
  company_name text null,
  occupant_kind text null,
  occupant_name text null,
  occupant_phone text null,
  occupant_email text null,
  occupant_until date null,
  purpose text null,
  ideal_parts_percent numeric null,
  ideal_parts_source text null,
