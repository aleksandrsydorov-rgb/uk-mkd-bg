create index if not exists properties_apartment_number_idx
  on public.properties (apartment_number);

-- Water meters (no-op when present)
create table if not exists public.water_meters (
  id uuid primary key default gen_random_uuid(),
  property_id bigint not null
    references public.properties (id) on delete restrict,
  meter_number text not null,
  initial_reading numeric(12, 3) not null,
  installed_at date not null default current_date,
  retired_at timestamptz null,
  replacement_reason text null,
  assigned_by_email text null,
  created_at timestamptz not null default now(),
  constraint water_meters_meter_number_not_blank
    check (length(trim(meter_number)) > 0),
  constraint water_meters_initial_reading_nonneg
    check (initial_reading >= 0),
  constraint water_meters_meter_number_key
    unique (meter_number),
  constraint water_meters_property_id_id_key
    unique (property_id, id)
);

create unique index if not exists water_meters_one_active_per_property_idx
  on public.water_meters (property_id)
  where retired_at is null;

create index if not exists water_meters_property_id_idx
  on public.water_meters (property_id);

-- Electricity meters (no-op when present)
create table if not exists public.electricity_meters (
  id uuid primary key default gen_random_uuid(),
  property_id bigint not null
    references public.properties (id) on delete restrict,
  meter_number text not null,
  initial_day_reading numeric(12, 3) not null,
  initial_night_reading numeric(12, 3) not null,
  installed_at date not null,
  retired_at date null,
  replacement_reason text null,
  assigned_by_email text not null,
  created_at timestamptz not null default now(),
  constraint electricity_meters_meter_number_not_blank
    check (length(trim(meter_number)) > 0),
  constraint electricity_meters_initial_day_nonneg
    check (initial_day_reading >= 0),
  constraint electricity_meters_initial_night_nonneg
    check (initial_night_reading >= 0),
  constraint electricity_meters_assigned_by_not_blank
    check (length(trim(assigned_by_email)) > 0),
  constraint electricity_meters_meter_number_key
    unique (meter_number)
);

create unique index if not exists electricity_meters_one_active_per_property_idx
  on public.electricity_meters (property_id)
  where retired_at is null;

create index if not exists electricity_meters_property_id_idx
  on public.electricity_meters (property_id);

-- RLS enable + grants; create SELECT policies only if missing and helpers exist
alter table public.water_meters enable row level security;
alter table public.electricity_meters enable row level security;

revoke all on table public.water_meters from public;
revoke all on table public.water_meters from anon;
revoke all on table public.electricity_meters from public;
revoke all on table public.electricity_meters from anon;

grant select on table public.water_meters to authenticated;
grant select on table public.electricity_meters to authenticated;

do $$
begin
  if to_regprocedure('public.has_staff_role(text)') is not null
     and to_regprocedure('public.owns_property(bigint)') is not null then
    if not exists (
      select 1 from pg_policies
      where schemaname = 'public'
        and tablename = 'water_meters'
        and policyname = 'water_meters_select'
    ) then
      create policy water_meters_select
      on public.water_meters
      for select
      to authenticated
      using (
        public.owns_property(property_id)
        or public.has_staff_role('администрация')
        or public.has_staff_role('бухгалтер')
        or public.has_staff_role('инженер')
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public'
        and tablename = 'electricity_meters'
        and policyname = 'electricity_meters_select'
    ) then
      create policy electricity_meters_select
      on public.electricity_meters
      for select
      to authenticated
      using (
        public.owns_property(property_id)
        or public.has_staff_role('администрация')
        or public.has_staff_role('бухгалтер')
        or public.has_staff_role('инженер')
      );
    end if;
  end if;
end $$;
