create or replace function public.property_book_owner_identity_creatable(p_own jsonb)
returns boolean
language plpgsql
immutable
set search_path = ''
as $fn$
declare
  v_kind text := lower(btrim(coalesce(p_own ->> 'entity_kind', '')));
begin
  if v_kind = 'legal_entity' then
    return nullif(btrim(coalesce(p_own ->> 'entity_name', '')), '') is not null;
  elsif v_kind = 'natural_person' then
    return nullif(btrim(coalesce(p_own ->> 'first_name', '')), '') is not null
       and nullif(btrim(coalesce(p_own ->> 'last_name', '')), '') is not null;
  elsif v_kind = 'sole_trader' then
    return nullif(btrim(coalesce(p_own ->> 'entity_name', '')), '') is not null
       or (
         nullif(btrim(coalesce(p_own ->> 'first_name', '')), '') is not null
         and nullif(btrim(coalesce(p_own ->> 'last_name', '')), '') is not null
       );
  end if;
  return false;
end;
$fn$;

revoke all on function public.property_book_owner_identity_creatable(jsonb) from public, anon;
grant execute on function public.property_book_owner_identity_creatable(jsonb) to authenticated;
grant execute on function public.property_book_owner_identity_creatable(jsonb) to service_role;

create or replace function public.property_book_filter_creatable_owners(p_owners jsonb)
returns jsonb
language plpgsql
stable
set search_path = ''
as $fn$
declare
  v_own jsonb;
  v_out jsonb := '[]'::jsonb;
begin
  if p_owners is null or jsonb_typeof(p_owners) <> 'array' then
    return '[]'::jsonb;
  end if;
  for v_own in select value from jsonb_array_elements(p_owners) as t(value)
  loop
    if public.property_book_owner_identity_creatable(v_own) then
      v_out := v_out || jsonb_build_array(v_own);
    end if;
  end loop;
  return v_out;
end;
$fn$;

revoke all on function public.property_book_filter_creatable_owners(jsonb) from public, anon;
grant execute on function public.property_book_filter_creatable_owners(jsonb) to authenticated;
grant execute on function public.property_book_filter_creatable_owners(jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- Soft vs hard validation
-- ---------------------------------------------------------------------------

create or replace function public.property_book_validate_owners_payload(
  p_purpose text,
  p_area_sqm numeric,
  p_ideal_parts_percent numeric,
  p_ownership_type text,
  p_owners jsonb
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  v_hard text[] := array[]::text[];
  v_soft text[] := array[]::text[];
  v_own jsonb;
  v_share_sum numeric := 0;
  v_ideal_sum numeric := 0;
  v_natural_n integer := 0;
  v_legal_n integer := 0;
  v_owner_n integer := 0;
  v_creatable_n integer := 0;
  v_kind text;
  v_share numeric;
  v_ideal numeric;
  v_own_type text := lower(btrim(coalesce(p_ownership_type, '')));
  v_prop_ideal numeric := p_ideal_parts_percent;
  v_has_any_share boolean := false;
  v_has_any_ideal boolean := false;
begin
  if p_owners is null or jsonb_typeof(p_owners) <> 'array' then
    return jsonb_build_object(
      'ok', false,
      'importable', true,
      'errors', '[]'::jsonb,
      'warnings', jsonb_build_array('owners_required'),
      'owner_count', 0,
      'creatable_owner_count', 0,
      'share_sum', 0,
      'ideal_sum', 0
    );
  end if;

  if nullif(btrim(coalesce(p_purpose, '')), '') is null then
    v_soft := array_append(v_soft, 'purpose_required');
  end if;
  if p_area_sqm is null or p_area_sqm <= 0 then
    v_soft := array_append(v_soft, 'area_required');
  end if;
  if v_prop_ideal is null then
    v_soft := array_append(v_soft, 'object_ideal_parts_required');
  end if;
  if v_own_type is null or v_own_type not in ('sole', 'shared') then
    v_soft := array_append(v_soft, 'ownership_type_required');
  end if;

  for v_own in select value from jsonb_array_elements(p_owners) as t(value)
  loop
    v_owner_n := v_owner_n + 1;
    if public.property_book_owner_identity_creatable(v_own) then
      v_creatable_n := v_creatable_n + 1;
    end if;

    begin
      v_share := nullif(btrim(coalesce(v_own ->> 'ownership_share_percent', '')), '')::numeric;
    exception when others then
      v_hard := array_append(v_hard, 'owner_share_invalid');
      v_share := null;
    end;
    if v_share is null or v_share <= 0 then
      v_soft := array_append(v_soft, 'owner_share_required');
    else
      v_has_any_share := true;
      v_share_sum := v_share_sum + v_share;
    end if;

    begin
      v_ideal := nullif(btrim(coalesce(v_own ->> 'ideal_parts_percent', '')), '')::numeric;
    exception when others then
      v_hard := array_append(v_hard, 'owner_ideal_parts_invalid');
      v_ideal := null;
    end;
    if v_ideal is null or v_ideal < 0 then
      v_soft := array_append(v_soft, 'owner_ideal_parts_required');
    else
      v_has_any_ideal := true;
      v_ideal_sum := v_ideal_sum + v_ideal;
    end if;

    if nullif(btrim(coalesce(v_own ->> 'email', '')), '') is null then
      v_soft := array_append(v_soft, 'owner_email_required');
    end if;

    v_kind := lower(btrim(coalesce(v_own ->> 'entity_kind', '')));
    if v_kind = 'legal_entity' then
      v_legal_n := v_legal_n + 1;
      if nullif(btrim(coalesce(v_own ->> 'entity_name', '')), '') is null then
        v_soft := array_append(v_soft, 'legal_name_required');
      end if;
      if nullif(btrim(coalesce(v_own ->> 'eik_bulstat', '')), '') is null then
        v_soft := array_append(v_soft, 'eik_required');
      end if;
    elsif v_kind in ('natural_person', 'sole_trader') then
      v_natural_n := v_natural_n + 1;
      if v_kind = 'natural_person'
         and (
           nullif(btrim(coalesce(v_own ->> 'first_name', '')), '') is null
           or nullif(btrim(coalesce(v_own ->> 'last_name', '')), '') is null
         ) then
        v_soft := array_append(v_soft, 'natural_name_required');
      end if;
      if v_kind = 'sole_trader'
         and nullif(btrim(coalesce(v_own ->> 'entity_name', '')), '') is null
         and (
           nullif(btrim(coalesce(v_own ->> 'first_name', '')), '') is null
           or nullif(btrim(coalesce(v_own ->> 'last_name', '')), '') is null
         ) then
        v_soft := array_append(v_soft, 'sole_trader_name_required');
      end if;
    elsif v_kind = '' then
      v_soft := array_append(v_soft, 'entity_kind_required');
    else
      v_hard := array_append(v_hard, 'invalid_entity_kind');
    end if;
  end loop;

  if v_owner_n = 0 or v_creatable_n = 0 then
    v_soft := array_append(v_soft, 'owners_required');
    if v_owner_n > 0 and v_creatable_n = 0 then
      v_soft := array_append(v_soft, 'ownership_identity_incomplete');
    end if;
  else
    if v_legal_n > 0 and v_natural_n > 0 then
      v_hard := array_append(v_hard, 'mixed_natural_legal_forbidden');
    end if;

    if v_own_type = 'sole' then
      if v_owner_n <> 1 then
        v_hard := array_append(v_hard, 'sole_requires_one_owner');
      elsif v_has_any_share and abs(v_share_sum - 100) > 0.01 then
        v_hard := array_append(v_hard, 'sole_share_must_be_100');
      end if;
      if v_prop_ideal is not null
         and v_owner_n = 1
         and v_has_any_ideal
         and abs(v_ideal_sum - v_prop_ideal) > 0.01 then
        v_hard := array_append(v_hard, 'sole_ideal_parts_mismatch');
      end if;
      if v_legal_n = 1 and v_has_any_share and abs(v_share_sum - 100) > 0.01 then
        v_hard := array_append(v_hard, 'legal_must_own_100');
      end if;
    elsif v_own_type = 'shared' then
      if v_owner_n < 2 then
        v_hard := array_append(v_hard, 'shared_requires_two_owners');
      elsif v_creatable_n < 2 then
        v_soft := array_append(v_soft, 'ownership_identity_incomplete');
      end if;
      if v_has_any_share and abs(v_share_sum - 100) > 0.01 then
        v_hard := array_append(v_hard, 'shares_must_sum_100');
      end if;
      if v_prop_ideal is not null and v_has_any_ideal and abs(v_ideal_sum - v_prop_ideal) > 0.01 then
        v_hard := array_append(v_hard, 'owner_ideal_parts_sum_mismatch');
      end if;
    end if;
  end if;

  select coalesce(array_agg(distinct e), array[]::text[]) into v_hard from unnest(v_hard) as e;
  select coalesce(array_agg(distinct e), array[]::text[]) into v_soft from unnest(v_soft) as e;

  return jsonb_build_object(
    'ok', coalesce(array_length(v_hard, 1), 0) = 0 and coalesce(array_length(v_soft, 1), 0) = 0,
    'importable', coalesce(array_length(v_hard, 1), 0) = 0,
    'errors', to_jsonb(v_hard),
    'warnings', to_jsonb(v_soft),
    'owner_count', v_owner_n,
    'creatable_owner_count', v_creatable_n,
    'share_sum', v_share_sum,
    'ideal_sum', v_ideal_sum
  );
end;
$fn$;

revoke all on function public.property_book_validate_owners_payload(text, numeric, numeric, text, jsonb) from public;
revoke all on function public.property_book_validate_owners_payload(text, numeric, numeric, text, jsonb) from anon;
grant execute on function public.property_book_validate_owners_payload(text, numeric, numeric, text, jsonb) to authenticated;
grant execute on function public.property_book_validate_owners_payload(text, numeric, numeric, text, jsonb) to service_role;

-- ---------------------------------------------------------------------------
-- Live clarification issues (status from data, not manual flags)
-- ---------------------------------------------------------------------------

create or replace function public.property_book_clarification_issues(p_property_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  v_prop public.properties%rowtype;
  v_owners jsonb := '[]'::jsonb;
  v_validation jsonb;
  v_issues jsonb := '[]'::jsonb;
  v_code text;
  v_own jsonb;
  v_idx integer := 0;
begin
  select p.* into v_prop
  from public.properties as p
  where p.id = p_property_id;
  if not found then
    return jsonb_build_object(
      'needs_clarification', false,
      'importable', false,
      'issues', jsonb_build_array(jsonb_build_object(
        'scope', 'property', 'code', 'property_not_found', 'field', 'property_id'
      ))
    );
  end if;

  select coalesce(jsonb_agg(to_jsonb(r) order by r.id), '[]'::jsonb)
    into v_owners
  from public.property_registry_people as r
  where r.property_id = p_property_id
    and r.relation_type = 'owner'
    and r.deregistered_at is null;

  v_validation := public.property_book_validate_owners_payload(
    v_prop.purpose,
    v_prop.area_sqm,
    v_prop.ideal_parts_percent,
    v_prop.ownership_type,
    v_owners
  );

  for v_code in
    select jsonb_array_elements_text(coalesce(v_validation -> 'warnings', '[]'::jsonb))
  loop
    v_issues := v_issues || jsonb_build_array(jsonb_build_object(
      'scope', case
        when v_code like 'owner_%' or v_code in (
          'natural_name_required', 'legal_name_required', 'eik_required',
          'sole_trader_name_required', 'entity_kind_required', 'owners_required',
          'ownership_identity_incomplete'
        ) then 'owner'
        else 'property'
      end,
      'code', v_code,
      'field', case v_code
        when 'purpose_required' then 'purpose'
        when 'area_required' then 'area_sqm'
        when 'object_ideal_parts_required' then 'ideal_parts_percent'
        when 'ownership_type_required' then 'ownership_type'
        when 'owner_email_required' then 'email'
        when 'owner_share_required' then 'ownership_share_percent'
        when 'owner_ideal_parts_required' then 'ideal_parts_percent'
        when 'natural_name_required' then 'first_name'
        when 'legal_name_required' then 'entity_name'
        when 'eik_required' then 'eik_bulstat'
        when 'owners_required' then 'owners'
        else v_code
      end
    ));
  end loop;

  for v_own in select value from jsonb_array_elements(v_owners) as t(value)
  loop
    v_idx := v_idx + 1;
    if nullif(btrim(coalesce(v_own ->> 'email', '')), '') is null then
      v_issues := v_issues || jsonb_build_array(jsonb_build_object(
        'scope', 'owner',
        'code', 'owner_email_required',
        'field', 'email',
        'registry_people_id', (v_own ->> 'id')::bigint,
        'owner_index', v_idx,
        'label', coalesce(
          nullif(btrim(concat_ws(' ', v_own ->> 'first_name', v_own ->> 'last_name')), ''),
          nullif(btrim(coalesce(v_own ->> 'entity_name', '')), ''),
          format('owner#%s', v_idx)
        )
      ));
    end if;
  end loop;

  -- Deduplicate by code+registry_people_id+field
  select coalesce(jsonb_agg(distinct_issue order by distinct_issue ->> 'code'), '[]'::jsonb)
    into v_issues
  from (
    select distinct on (
      coalesce(i ->> 'code', ''),
      coalesce(i ->> 'registry_people_id', ''),
      coalesce(i ->> 'field', '')
    ) i as distinct_issue
    from jsonb_array_elements(v_issues) as e(i)
    order by
      coalesce(i ->> 'code', ''),
      coalesce(i ->> 'registry_people_id', ''),
      coalesce(i ->> 'field', '')
  ) d;

  return jsonb_build_object(
    'needs_clarification', jsonb_array_length(v_issues) > 0,
    'importable', coalesce((v_validation ->> 'importable')::boolean, false),
    'book_complete', coalesce((v_validation ->> 'ok')::boolean, false),
    'hard_errors', coalesce(v_validation -> 'errors', '[]'::jsonb),
    'issues', v_issues
  );
end;
$fn$;

revoke all on function public.property_book_clarification_issues(bigint) from public, anon;
grant execute on function public.property_book_clarification_issues(bigint) to authenticated;
grant execute on function public.property_book_clarification_issues(bigint) to service_role;

-- ---------------------------------------------------------------------------
-- owns_property: access-ready OR accepted invite (incomplete invited owners)
-- ---------------------------------------------------------------------------

create or replace function public.owns_property(property_id bigint)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  v_email text := lower(nullif(btrim(coalesce(auth.email(), '')), ''));
  v_owner public.property_registry_people%rowtype;
begin
  if v_email is null or auth.uid() is null then
    return false;
  end if;

  v_owner := public.property_book_active_owner_by_email(property_id, v_email);
  if v_owner.id is null then
    return false;
  end if;
  if public.property_book_owner_row_access_ready(v_owner) then
    return true;
  end if;

  return exists (
    select 1
    from public.property_access_invites as i
    where i.property_id = property_id
      and i.registry_people_id = v_owner.id
      and i.status = 'accepted'
      and lower(btrim(coalesce(i.email, ''))) = v_email
  );
end;
$fn$;

revoke all on function public.owns_property(bigint) from public, anon;
grant execute on function public.owns_property(bigint) to authenticated;

-- ---------------------------------------------------------------------------
-- Import: hard errors abort; soft warnings import with clarification
-- ---------------------------------------------------------------------------

create or replace function public.admin_import_property_book(
  p_objects jsonb,
  p_owners jsonb,
  p_dry_run boolean default true,
  p_allow_create_missing boolean default false,
  p_allow_overwrite boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_obj jsonb;
  v_own jsonb;
  v_apt text;
  v_apt_num bigint;
  v_prop_id bigint;
  v_errors jsonb := '[]'::jsonb;
  v_warnings jsonb := '[]'::jsonb;
  v_existing jsonb := '[]'::jsonb;
  v_new_props jsonb := '[]'::jsonb;
  v_changes jsonb := '[]'::jsonb;
  v_duplicates jsonb := '[]'::jsonb;
  v_touched bigint[] := array[]::bigint[];
  v_created bigint[] := array[]::bigint[];
  v_skipped_identical bigint[] := array[]::bigint[];
  v_owners_by_apt jsonb := '{}'::jsonb;
  v_list jsonb;
  v_validation jsonb;
  v_ok_count integer := 0;
  v_importable_count integer := 0;
  v_clarification_count integer := 0;
  v_purpose text;
  v_area numeric;
  v_ideal numeric;
  v_own_type text;
  v_floor bigint;
  v_section text;
  v_block text;
  v_seen_apts text[] := array[]::text[];
  v_prop public.properties%rowtype;
  v_would_create boolean;
  v_would_change boolean;
  v_identical boolean;
  v_owner_count int;
  v_allow_create boolean;
  v_expected_count integer;
  v_unique_count integer;
  v_book_empty boolean;
  v_creatable jsonb;
  v_hard jsonb;
  v_soft jsonb;
  v_code text;
begin
  perform public.admin_assert_book_admin();
  perform public.property_book_set_mutating(true);

  if p_objects is null or jsonb_typeof(p_objects) <> 'array' then
    raise exception 'admin_import_property_book: objects array required'
      using errcode = '22023';
  end if;
  if p_owners is null or jsonb_typeof(p_owners) <> 'array' then
    raise exception 'admin_import_property_book: owners array required'
      using errcode = '22023';
  end if;

  select not exists (select 1 from public.properties limit 1) into v_book_empty;
  v_allow_create := coalesce(p_allow_create_missing, false) or v_book_empty;

  select i.apartment_count
  into v_expected_count
  from public.platform_installations as i
  where i.id = public.first_run_default_installation_id();

  for v_own in select value from jsonb_array_elements(p_owners) as t(value)
  loop
    v_apt := nullif(btrim(coalesce(v_own ->> 'apartment_number', '')), '');
    if v_apt is null then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'owners',
        'row', coalesce((v_own ->> '_row')::int, null),
        'field', 'apartment_number',
        'code', 'apartment_number_required',
        'reason', 'apartment_number_required',
        'severity', 'error',
        'row_data', v_own
      ));
      continue;
    end if;
    v_list := coalesce(v_owners_by_apt -> v_apt, '[]'::jsonb);
    v_owners_by_apt := jsonb_set(
      v_owners_by_apt,
      array[v_apt],
      v_list || jsonb_build_array(v_own)
    );
  end loop;

  for v_obj in select value from jsonb_array_elements(p_objects) as t(value)
  loop
    v_would_create := false;
    v_would_change := false;
    v_identical := false;
    v_apt := nullif(btrim(coalesce(v_obj ->> 'apartment_number', '')), '');
    if v_apt is null then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects',
        'row', coalesce((v_obj ->> '_row')::int, null),
        'field', 'apartment_number',
        'code', 'apartment_number_required',
        'reason', 'apartment_number_required',
        'severity', 'error'
      ));
      continue;
    end if;

    if v_apt = any (v_seen_apts) then
      v_duplicates := v_duplicates || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects', 'code', 'duplicate_apartment', 'apartment_number', v_apt
      ));
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects',
        'row', coalesce((v_obj ->> '_row')::int, null),
        'field', 'apartment_number',
        'code', 'duplicate_apartment',
        'reason', 'duplicate_apartment',
        'severity', 'error',
        'apartment_number', v_apt
      ));
      continue;
    end if;
    v_seen_apts := array_append(v_seen_apts, v_apt);

    begin
      v_apt_num := v_apt::bigint;
    exception when others then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects',
        'field', 'apartment_number',
        'code', 'apartment_number_invalid',
        'reason', 'apartment_number_invalid',
        'severity', 'error',
        'apartment_number', v_apt
      ));
      continue;
    end;

    v_purpose := nullif(btrim(coalesce(v_obj ->> 'purpose', '')), '');
    begin
      v_area := nullif(btrim(coalesce(v_obj ->> 'area_sqm', '')), '')::numeric;
    exception when others then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects', 'field', 'area_sqm', 'code', 'area_sqm_invalid',
        'reason', 'area_sqm_invalid', 'severity', 'error', 'apartment_number', v_apt
      ));
      continue;
    end;
    begin
      v_ideal := nullif(btrim(coalesce(v_obj ->> 'ideal_parts_percent', '')), '')::numeric;
    exception when others then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects', 'field', 'ideal_parts_percent', 'code', 'ideal_parts_invalid',
        'reason', 'ideal_parts_invalid', 'severity', 'error', 'apartment_number', v_apt
      ));
      continue;
    end;
    v_own_type := nullif(btrim(coalesce(v_obj ->> 'ownership_type', '')), '');
    if v_own_type is not null and v_own_type not in ('sole', 'shared') then
      v_errors := v_errors || jsonb_build_array(jsonb_build_object(
        'sheet', 'objects', 'field', 'ownership_type', 'code', 'ownership_type_invalid',
        'reason', 'ownership_type_invalid', 'severity', 'error', 'apartment_number', v_apt
      ));
      continue;
    end if;
    v_section := nullif(btrim(coalesce(v_obj ->> 'section_code', '')), '');
    v_block := nullif(btrim(coalesce(v_obj ->> 'block_code', '')), '');
    begin
      v_floor := nullif(btrim(coalesce(v_obj ->> 'floor', '')), '')::bigint;
    exception when others then
      v_floor := null;
    end;

    select p.* into v_prop
    from public.properties as p
    where p.apartment_number = v_apt
    limit 1;

    if not found then
      v_would_create := true;
      v_new_props := v_new_props || jsonb_build_array(jsonb_build_object(
        'apartment_number', v_apt,
        'purpose', v_purpose,
        'area_sqm', v_area,
        'ideal_parts_percent', v_ideal,
        'ownership_type', v_own_type
      ));
      if not v_allow_create and not coalesce(p_dry_run, true) then
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
          'sheet', 'objects',
          'field', 'apartment_number',
          'code', 'create_missing_requires_confirmation',
          'reason', 'create_missing_requires_confirmation',
          'severity', 'error',
          'apartment_number', v_apt
        ));
        continue;
      end if;
      v_prop_id := null;
    else
      v_prop_id := v_prop.id;
      v_existing := v_existing || jsonb_build_array(jsonb_build_object(
        'property_id', v_prop.id,
        'apartment_number', v_apt
      ));

      select count(*)::int into v_owner_count
      from public.property_registry_people as r
      where r.property_id = v_prop.id
        and r.relation_type = 'owner'
        and r.deregistered_at is null;

      if (v_purpose is distinct from v_prop.purpose)
         or (v_area is distinct from v_prop.area_sqm)
         or (v_ideal is distinct from v_prop.ideal_parts_percent)
         or (v_own_type is distinct from v_prop.ownership_type)
         or (v_section is distinct from v_prop.section_code)
         or (v_block is distinct from v_prop.block_code)
         or (v_floor is distinct from v_prop.floor)
         or coalesce(jsonb_array_length(v_owners_by_apt -> v_apt), 0) <> v_owner_count
      then
        v_would_change := true;
        v_changes := v_changes || jsonb_build_array(jsonb_build_object(
          'property_id', v_prop.id,
          'apartment_number', v_apt,
          'object_fields_differ', true,
          'owners_in_file', coalesce(jsonb_array_length(v_owners_by_apt -> v_apt), 0),
          'active_owners_now', v_owner_count
        ));
      else
        v_identical := true;
      end if;

      if v_would_change
         and not coalesce(p_allow_overwrite, false)
         and not coalesce(p_dry_run, true) then
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
          'sheet', 'objects',
          'field', 'apartment_number',
          'code', 'overwrite_requires_confirmation',
          'reason', 'overwrite_requires_confirmation',
          'severity', 'error',
          'apartment_number', v_apt,
          'property_id', v_prop.id
        ));
        continue;
      end if;
    end if;

    v_validation := public.property_book_validate_owners_payload(
      v_purpose,
      v_area,
      v_ideal,
      v_own_type,
      coalesce(v_owners_by_apt -> v_apt, '[]'::jsonb)
    );
    v_hard := coalesce(v_validation -> 'errors', '[]'::jsonb);
    v_soft := coalesce(v_validation -> 'warnings', '[]'::jsonb);

    if jsonb_array_length(v_hard) > 0 then
      for v_code in select jsonb_array_elements_text(v_hard)
      loop
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
          'sheet', 'validation',
          'field', 'owners',
          'apartment_number', v_apt,
          'code', v_code,
          'codes', v_hard,
          'reason', v_code,
          'severity', 'error'
        ));
      end loop;
      v_identical := false;
    elsif jsonb_array_length(v_soft) > 0 then
      for v_code in select jsonb_array_elements_text(v_soft)
      loop
        v_warnings := v_warnings || jsonb_build_array(jsonb_build_object(
          'sheet', 'validation',
          'field', case v_code
            when 'purpose_required' then 'purpose'
            when 'area_required' then 'area_sqm'
            when 'object_ideal_parts_required' then 'ideal_parts_percent'
            when 'ownership_type_required' then 'ownership_type'
            when 'owner_email_required' then 'email'
            when 'owners_required' then 'owners'
            else 'owners'
          end,
          'apartment_number', v_apt,
          'code', v_code,
          'reason', v_code,
          'severity', 'warning'
        ));
      end loop;
    end if;

    if coalesce(p_dry_run, true) then
      if jsonb_array_length(v_hard) = 0 then
        v_importable_count := v_importable_count + 1;
        if jsonb_array_length(v_soft) > 0 then
          v_clarification_count := v_clarification_count + 1;
        elsif coalesce((v_validation ->> 'ok')::boolean, false) then
          v_ok_count := v_ok_count + 1;
        end if;
      end if;
      continue;
    end if;

    if jsonb_array_length(v_hard) > 0 then
      continue;
    end if;

    if v_identical and not v_would_create and not coalesce(p_allow_overwrite, false) then
      v_importable_count := v_importable_count + 1;
      if jsonb_array_length(v_soft) > 0 then
        v_clarification_count := v_clarification_count + 1;
      else
        v_ok_count := v_ok_count + 1;
      end if;
      v_skipped_identical := array_append(v_skipped_identical, v_prop_id);
      v_touched := array_append(v_touched, v_prop_id);
      continue;
    end if;

    if v_would_create then
      if v_floor is null then
        v_floor := case
          when v_apt_num between 1 and 99 then 1
          else greatest(1, (v_apt_num / 100)::bigint)
        end;
      end if;
      insert into public.properties (
        apartment_number, floor, section_code, block_code,
        area_sqm, purpose, ideal_parts_percent, ownership_type, status
      ) values (
        v_apt, v_floor, v_section, v_block,
        v_area, v_purpose, v_ideal, v_own_type, 'vacant'
      )
      returning id into v_prop_id;
      v_created := array_append(v_created, v_prop_id);
    end if;

    -- Preserve filled values: blank import cells do not wipe existing on overwrite path
    -- unless allow_overwrite and the file cell was explicitly provided as empty for
    -- optional fields — object upsert still writes provided nulls only when overwrite.
    if coalesce(p_allow_overwrite, false) or v_would_create then
      perform public.admin_upsert_property_book_object(
        v_prop_id,
        case when v_would_create or v_purpose is not null then v_purpose else v_prop.purpose end,
        case when v_would_create or v_area is not null then v_area else v_prop.area_sqm end,
        case when v_would_create or v_ideal is not null then v_ideal else v_prop.ideal_parts_percent end,
        case when v_would_create or v_own_type is not null then v_own_type else v_prop.ownership_type end,
        v_obj ->> 'ideal_parts_source',
        v_apt_num,
        coalesce(v_floor, v_prop.floor),
        null,
        null,
        coalesce(v_section, v_prop.section_code),
        coalesce(v_block, v_prop.block_code)
      );

      v_creatable := public.property_book_filter_creatable_owners(
        coalesce(v_owners_by_apt -> v_apt, '[]'::jsonb)
      );
      -- Replace owners only when file has creatable rows, or create with empty,
      -- or overwrite explicitly requested (may clear non-creatable-only payloads).
      if jsonb_array_length(v_creatable) > 0
         or v_would_create
         or coalesce(p_allow_overwrite, false) then
        perform public.admin_replace_property_book_owners(v_prop_id, v_creatable);
      end if;
    end if;

    v_validation := public.property_book_validate(v_prop_id);
    v_importable_count := v_importable_count + 1;
    if coalesce((v_validation ->> 'ok')::boolean, false) then
      v_ok_count := v_ok_count + 1;
    elsif coalesce((v_validation ->> 'importable')::boolean, false) then
      v_clarification_count := v_clarification_count + 1;
    end if;

    v_touched := array_append(v_touched, v_prop_id);
  end loop;

  v_unique_count := coalesce(cardinality(v_seen_apts), 0);
  if v_expected_count is not null and v_unique_count <> v_expected_count then
    v_errors := v_errors || jsonb_build_array(jsonb_build_object(
      'sheet', 'objects',
      'field', 'apartment_count',
      'code', 'apartment_count_mismatch',
      'reason', 'apartment_count_mismatch',
      'severity', 'error',
      'expected', v_expected_count,
      'actual', v_unique_count
    ));
  end if;

  for v_apt in select jsonb_object_keys(v_owners_by_apt)
  loop
    if not exists (
      select 1
      from jsonb_array_elements(p_objects) as o(value)
      where btrim(coalesce(o.value ->> 'apartment_number', '')) = v_apt
    ) then
      -- Owner rows without object: hard only if apartment also missing from DB
      if not exists (
        select 1 from public.properties p where p.apartment_number = v_apt
      ) then
        v_errors := v_errors || jsonb_build_array(jsonb_build_object(
          'sheet', 'owners', 'field', 'apartment_number', 'code', 'object_row_missing',
          'reason', 'object_row_missing', 'severity', 'error', 'apartment_number', v_apt
        ));
      end if;
    end if;
  end loop;

  if not coalesce(p_dry_run, true) and jsonb_array_length(v_errors) > 0 then
    raise exception 'admin_import_property_book: apply aborted - % errors', jsonb_array_length(v_errors)
      using errcode = 'P0001',
            detail = v_errors::text;
  end if;

  return jsonb_build_object(
    'dry_run', coalesce(p_dry_run, true),
    'ok', jsonb_array_length(v_errors) = 0,
    'errors', v_errors,
    'warnings', v_warnings,
    'existing_properties', v_existing,
    'new_properties', v_new_props,
    'changes', v_changes,
    'duplicates', v_duplicates,
    'requires_create_confirmation', jsonb_array_length(v_new_props) > 0 and not v_book_empty,
    'requires_overwrite_confirmation', jsonb_array_length(v_changes) > 0,
    'allow_create_missing', v_allow_create,
    'allow_overwrite', coalesce(p_allow_overwrite, false),
    'book_empty_auto_create', v_book_empty,
    'expected_apartment_count', v_expected_count,
    'unique_apartment_count', v_unique_count,
    'touched_property_ids', to_jsonb(v_touched),
    'created_property_ids', to_jsonb(v_created),
    'skipped_identical_property_ids', to_jsonb(v_skipped_identical),
    'complete_count', v_ok_count,
    'importable_count', v_importable_count,
    'clarification_count', v_clarification_count,
    'blocking_error_count', jsonb_array_length(v_errors)
  );
end;
$fn$;

revoke all on function public.admin_import_property_book(jsonb, jsonb, boolean, boolean, boolean) from public, anon;
