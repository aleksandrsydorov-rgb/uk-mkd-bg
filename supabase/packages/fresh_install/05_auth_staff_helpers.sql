-- IS-9a fresh-install package — staff shell + authorization helpers
-- =============================================================================
-- Empty-project bootstrap ONLY (apply before supabase/migrations/).
-- Idempotent. No administrator rows. No passwords. No credentials.
-- First administrator bootstrap remains a controlled future installation step.
-- =============================================================================

create table if not exists public.staff (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text null,
  phone text null,
  role text not null,
  salary_eur numeric null,
  active boolean null default true,
  constraint staff_role_canonical_chk
    check (role in ('администрация', 'бухгалтер', 'инженер', 'уборщик'))
);

comment on table public.staff is
  'IS-9a baseline: staff roster shell. Empty on fresh install — no default admin.';

create index if not exists staff_email_lower_idx
  on public.staff (lower(btrim(email)))
  where email is not null;

alter table public.staff enable row level security;

revoke all on table public.staff from public;
revoke all on table public.staff from anon;
revoke all on table public.staff from authenticated;

grant select (id, created_at, name, email, phone, role, active)
  on table public.staff to authenticated;
grant insert, update, delete on table public.staff to authenticated;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff as s
    where lower(btrim(s.email)) = lower(btrim(auth.email()))
      and s.active is true
      and s.role in ('администрация', 'бухгалтер', 'инженер', 'уборщик')
  );
$$;

revoke all on function public.is_staff() from public;
revoke execute on function public.is_staff() from anon;
grant execute on function public.is_staff() to authenticated;

create or replace function public.has_staff_role(p_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    p_role in ('администрация', 'бухгалтер', 'инженер', 'уборщик')
    and exists (
      select 1
      from public.staff as s
      where lower(btrim(s.email)) = lower(btrim(auth.email()))
        and s.active is true
        and s.role = p_role
    );
$$;

revoke all on function public.has_staff_role(text) from public;
revoke execute on function public.has_staff_role(text) from anon;
grant execute on function public.has_staff_role(text) to authenticated;

-- Governance helper (legacy documents_decisions_hotfix). Required before SH-2C1
-- meeting-file policies; thin wrapper over exact active administration role.
create or replace function public.can_manage_building_governance()
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select public.has_staff_role('администрация');
$fn$;

revoke all on function public.can_manage_building_governance() from public;
revoke execute on function public.can_manage_building_governance() from anon;
grant execute on function public.can_manage_building_governance() to authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'staff' and policyname = 'staff_select'
  ) then
    create policy staff_select
    on public.staff
    for select
    to authenticated
    using (public.is_staff());
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'staff' and policyname = 'staff_admin_insert'
  ) then
    create policy staff_admin_insert
    on public.staff
    for insert
    to authenticated
    with check (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'staff' and policyname = 'staff_admin_update'
  ) then
    create policy staff_admin_update
    on public.staff
    for update
    to authenticated
    using (public.has_staff_role('администрация'))
    with check (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'staff' and policyname = 'staff_admin_delete'
  ) then
    create policy staff_admin_delete
    on public.staff
    for delete
    to authenticated
    using (public.has_staff_role('администрация'));
  end if;
end $$;

