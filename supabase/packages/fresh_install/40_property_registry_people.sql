-- =============================================================================
-- IS-9a fresh-install package — Property Book registry people baseline
-- =============================================================================
-- Canonical tables only. No production apartment/owner/building rows.
-- Ideal parts / ownership shares live as columns; Book RPCs remain a gap.
-- =============================================================================

create table if not exists public.property_registry_people (
  id bigint generated by default as identity primary key,
  property_id integer not null
    references public.properties (id) on delete cascade,
  relation_type text not null,
  entity_kind text not null default 'natural_person',
  first_name text,
  middle_name text,
  last_name text,
  entity_name text,
  eik_bulstat text,
  email text,
  registered_at date,
  deregistered_at date,
  lives_on_property boolean,
  note text,
  ownership_share_percent numeric(12, 6) null,
  ideal_parts_percent numeric(12, 6) null,
  admin_status text not null default 'active',
  voting_eligible boolean not null default true,
  death_document_type text null,
  death_document_number text null,
  death_document_date date null,
  death_document_path text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint property_registry_people_relation_chk
    check (relation_type in (
      'owner',
      'user_of_property',
      'household_member',
      'occupant'
    )),
  constraint property_registry_people_entity_chk
    check (entity_kind in (
      'natural_person',
      'legal_entity',
      'sole_trader'
    )),
  constraint property_registry_people_dates_chk
    check (deregistered_at is null or registered_at is null or deregistered_at >= registered_at),
  constraint property_registry_people_natural_name_chk
    check (
      entity_kind <> 'natural_person'
      or (
        btrim(coalesce(first_name, '')) <> ''
        and btrim(coalesce(last_name, '')) <> ''
      )
    ),
  constraint property_registry_people_legal_name_chk
    check (
      entity_kind = 'natural_person'
      or btrim(coalesce(entity_name, '')) <> ''
    ),
  constraint property_registry_people_admin_status_chk
    check (admin_status in ('active', 'pending_inheritance', 'deceased_recorded'))
);

comment on table public.property_registry_people is
  'Legal condominium-book persons for a property. Ideal parts stay on properties and/or people columns, not invented shares.';

comment on column public.property_registry_people.ownership_share_percent is
  'Owner share of the unit (sums to 100% for active owners).';

comment on column public.property_registry_people.ideal_parts_percent is
  'Owner vote weight from the book (not computed at vote time).';

create index if not exists property_registry_people_property_idx
  on public.property_registry_people (property_id);

create index if not exists property_registry_people_relation_idx
  on public.property_registry_people (property_id, relation_type);

create index if not exists property_registry_people_owner_active_idx
  on public.property_registry_people (property_id)
  where relation_type = 'owner' and deregistered_at is null;

create table if not exists public.property_absence_periods (
  id bigint generated by default as identity primary key,
  property_id integer not null
    references public.properties (id) on delete cascade,
  person_id bigint
    references public.property_registry_people (id) on delete set null,
  from_date date not null,
  to_date date,
  note text,
  source text,
  created_at timestamptz not null default now(),
  constraint property_absence_periods_dates_chk
    check (to_date is null or to_date >= from_date)
);

create index if not exists property_absence_periods_property_idx
  on public.property_absence_periods (property_id);

alter table public.property_registry_people enable row level security;
alter table public.property_absence_periods enable row level security;

revoke all on table public.property_registry_people from public;
revoke all on table public.property_registry_people from anon;
revoke all on table public.property_registry_people from authenticated;
revoke all on table public.property_absence_periods from public;
revoke all on table public.property_absence_periods from anon;
revoke all on table public.property_absence_periods from authenticated;

grant select on table public.property_registry_people to authenticated;
grant select on table public.property_absence_periods to authenticated;
grant insert, update, delete on table public.property_registry_people to authenticated;
grant insert, update, delete on table public.property_absence_periods to authenticated;

-- Policies require Book-only owns_property + has_staff_role.
-- If owns_property is still a greenfield gap, RLS stays enabled with no policies
-- (safe deny for authenticated via revoke+grant select without USING policy
-- until helpers land from migrations / later package phase).
do $$
begin
  if to_regprocedure('public.has_staff_role(text)') is null then
    return;
  end if;

  -- Admin write policies (do not require owns_property).
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_registry_people'
      and policyname = 'property_registry_people_admin_write'
  ) then
    create policy property_registry_people_admin_write
    on public.property_registry_people
    for insert
    to authenticated
    with check (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_registry_people'
      and policyname = 'property_registry_people_admin_update'
  ) then
    create policy property_registry_people_admin_update
    on public.property_registry_people
    for update
    to authenticated
    using (public.has_staff_role('администрация'))
    with check (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_registry_people'
      and policyname = 'property_registry_people_admin_delete'
  ) then
    create policy property_registry_people_admin_delete
    on public.property_registry_people
    for delete
    to authenticated
    using (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_absence_periods'
      and policyname = 'property_absence_periods_admin_write'
  ) then
    create policy property_absence_periods_admin_write
    on public.property_absence_periods
    for insert
    to authenticated
    with check (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_absence_periods'
      and policyname = 'property_absence_periods_admin_update'
  ) then
    create policy property_absence_periods_admin_update
    on public.property_absence_periods
    for update
    to authenticated
    using (public.has_staff_role('администрация'))
    with check (public.has_staff_role('администрация'));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_absence_periods'
      and policyname = 'property_absence_periods_admin_delete'
  ) then
    create policy property_absence_periods_admin_delete
    on public.property_absence_periods
    for delete
    to authenticated
    using (public.has_staff_role('администрация'));
  end if;

  -- Owner/admin SELECT when Book-only owns_property is available.
  if to_regprocedure('public.owns_property(bigint)') is not null then
    if not exists (
      select 1 from pg_policies
      where schemaname = 'public'
        and tablename = 'property_registry_people'
        and policyname = 'property_registry_people_select'
    ) then
      create policy property_registry_people_select
      on public.property_registry_people
      for select
      to authenticated
      using (
        public.owns_property(property_id)
        or public.has_staff_role('администрация')
      );
    end if;

    if not exists (
      select 1 from pg_policies
      where schemaname = 'public'
        and tablename = 'property_absence_periods'
        and policyname = 'property_absence_periods_select'
    ) then
      create policy property_absence_periods_select
      on public.property_absence_periods
      for select
      to authenticated
      using (
        public.owns_property(property_id)
        or public.has_staff_role('администрация')
      );
    end if;
  elsif not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'property_registry_people'
      and policyname = 'property_registry_people_admin_select'
  ) then
    -- Interim: administration-only SELECT until owns_property is packaged.
    create policy property_registry_people_admin_select
    on public.property_registry_people
    for select
    to authenticated
    using (public.has_staff_role('администрация'));

    create policy property_absence_periods_admin_select
    on public.property_absence_periods
    for select
    to authenticated
    using (public.has_staff_role('администрация'));
  end if;
end $$;
